/* ============================================================
   从后台切回前台：要不要重拉一次
   ------------------------------------------------------------
   `tick()` 每 60 秒跑一次，但它**只在跨逻辑日时**才 `refresh()`
   （见 `store/useApp.ts` 的 `tick`）。所以「切回前台」并不会真的重拉数据 ——
   而 `App.tsx` 里那条注释一直写着「避免显示过期数据」。

   实际后果（都不报错）：平板放一边半天再拿起来，看到的还是半天前的任务和积分；
   家长在**另一台设备**上改了 PIN / 每日限时，这台要等到重启或跨日才生效。

   ★ 为什么不是「每次切回来都拉」：来回切 App 很常见（回个消息再切回来），
     每次都打一轮接口没必要。30 秒的闸门够用，也不影响「切回来就该是新的」。
   ============================================================ */

/** 最多这么频繁地重拉一次 */
export const FOREGROUND_REFRESH_GAP_MS = 30_000

/**
 * 这次切回前台该不该重拉。
 *
 * `lastAt = 0` 表示本进程还没拉过 ⇒ 第一次一定拉。
 * ⚠️ 判据是 `>=`：`lastAt` 和 `now` 同一毫秒（同一个 tick 里连发两次）时，
 * 差值是 0，不该放行 —— 但第一次（`lastAt === 0`）必须放行，所以单独判。
 */
export function shouldRefreshOnForeground(lastAt: number, now: number): boolean {
  if (lastAt <= 0) return true
  return now - lastAt >= FOREGROUND_REFRESH_GAP_MS
}
