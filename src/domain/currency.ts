/**
 * 三套币的**显示口径**唯一事实源（名字 + 图标 + 颜色档）。
 *
 * ## 为什么要有这个文件
 *
 * 2026-10-16 把「丰收币」改名成「点券」时，这个名字在 `src/` 里散着 **173 处**、
 * 图标 `🌾` 还额外散着 39 处。改一次名要动 23 个文件，而且**漏一处不会报错**
 * —— 只会界面上有一处还写着旧名字。
 *
 * 这正是本项目已经吃过几次亏的那个形态：「同一个事实存两份就一定会走散」。
 * 所以把口径收在这里，**新代码一律从这里取**。
 *
 * ## ⚠️ 只放「显示口径」，不放经济规则
 *
 * 这里没有余额、没有汇率、没有任何计算。余额永远是**算出来的**
 * （账本 delta 之和），汇率在 `domain/redeem.ts`。这个文件只回答
 * 「这个币叫什么、长什么样」。
 *
 * ## ⚠️ 老代码里还有字面量
 *
 * 改名时是**按行号精确替换**的（不能全局替换 —— `🌾` 同时是农作物的阶段图标、
 * 农场 tab 的图标）。所以老文件里仍写着字面量 `🎟️` / `🪙`。
 * 那些地方**行为是对的**，只是没走常量。新代码请用常量；
 * 顺手改到老文件时也可以换成常量（纯字符串，零风险）。
 */

/** 三套币的 id。和 `LedgerEntry` / `HarvestEntry` / 商城账本一一对应。 */
export type CurrencyId = 'points' | 'coupon' | 'mall'

export interface CurrencyDef {
  /** 界面上写的名字 */
  name: string
  /** 图标。三个**必须互不相同** —— 付款行是「图标 + 数字」并排的，重了就看不出在付哪种币 */
  emoji: string
  /** 用哪一档配色。见 `theme.css` 的色板 */
  tone: 'sun' | 'grass' | 'sky'
}

/**
 * ★★ **三套币互不相通**（spec §2.2）：
 *
 * ```
 *   积分  ⇸  点券      点券  ⇸  积分      商城币  ⇸  任何别的币
 * ```
 *
 * 唯一的例外是**兑换商城的付款口**：那里 `1 点券 ≡ 1 积分`
 * （`planRedeemPayment`：先用光点券，差额用积分补）。
 * 所以「点券」的产出速率必须受控 —— 见 `domain/clawEconomy.ts` 的期望值不变量。
 */
export const CURRENCY: Record<CurrencyId, CurrencyDef> = {
  points: { name: '积分', emoji: '🪙', tone: 'sun' },
  coupon: { name: '点券', emoji: '🎟️', tone: 'grass' },
  mall: { name: '商城币', emoji: '🛍️', tone: 'sky' },
}

/*
  ★ 2026-10-16：商城币的图标从 `🎫` 换成 `🛍️`。

  原来三套币是 `🪙` / `🎟️` / `🎫` —— 后两个是**两张票**，只差一个存根，
  16px 下基本看不出区别。而它们确实会同屏：

    · 设置页：商城币卡是 `🎫`，同一页「利润比」那张卡里点券写作 `🎟️`；
    · 兑换页更直接：付款行是「`🎟️` 250 + `🪙` 10」，而它上面那张奖励卡
      （种子数据「一次免做一项家务」）的图标就是 `🎫`。

  上面 `CurrencyDef.emoji` 写着「三个**必须互不相同**」，理由就是付款行是
  「图标 + 数字」并排的。既然做不到，就换掉那个**改动面最小**的：
  `🎫` 全项目只出现 5 处，`🎟️` 有 44 处（而且点券这个图标当天刚从 `🌾` 换过来，
  再换一次是拿改动换改动）。换 `🛍️` 顺带把语义也修对了 ——
  它叫「商城**币**」，本来就不该长成一张票。

  ⚠️ `🛍️` 的 `U+FE0F`（变体选择符）**不能省**：`U+1F6CD` 默认是文字样式，
  去掉就会渲染成一个单色的黑白袋子。省掉的那一版在 `grep` 里看着一模一样。

  ➕ 顺带把 `🎫` 从**非货币**的地方也清掉了：种子奖励「一次免做一项家务」的图标
  `🎫` → `🧹`（家务分类本来就是 `🧹`），家长选奖励图标的调色板里那一个也换成了 `🧹`。
  不清的话，奖励卡上那张 `🎫` 还是挨着付款行的 `🎟️`。现在 `🎫` 在 `src/` 里不再出现。
*/

