/**
 * 游戏的**分类**（设置 → 游戏 → 游戏市场里那两个小标题）。
 *
 * ## 为什么单独一个文件
 *
 * 内置游戏在 `registry.ts`、随包发的插件在 `storefront.ts`，两边都要这个字段。
 * 让它俩互相 import 是错的：注册表是「有哪些游戏」的事实，内容文件是
 * 「怎么介绍它」。所以分类单独拎出来，两边都 import 它。
 *
 * ## 口径：按**玩法性质**分，不按「有没有产出」分
 *
 * 现有三款插件**都**会产出兑换券（积分 → 游戏币 → 券），按产出分的话
 * 「纯玩」那一类是空的，等于白设一个分类。
 * 所以分类回答的是「玩起来是什么感觉」，而每一行上照样标真实的
 * 适龄 / 时长 / 体积 —— **分类是判断，数字是事实，两者不混**。
 *
 * ⚠️ 改这个字段之前先想清楚：它出现在家长看的那一页上，
 * 而家长用这一栏决定「给不给孩子玩」。
 */
export type GameKind = 'think' | 'play'

