/**
 * 三套币的**显示口径**唯一事实源（名字 + 图标 + 颜色档）。
 *
 * ## 为什么要有这个文件
 *
 * 改名在本项目里已经发生过两次：
 *   · 2026-10-16「丰收币」→「点券」（名字散着 **173 处**、图标 `🌾` 39 处，漏一处不报错）；
 *   · 2026-10-17 **链式改名**：「点券」→「商城币」、「商城币」→「钻石」
 *     （用户原话：「兑换券换成之前的游戏商城的券，而游戏商城的券换成钻石」）。
 *
 * 这正是本项目吃过几次亏的那个形态：「同一个事实存两份就一定会走散」。
 * 所以把口径收在这里，**新代码一律从这里取**。
 *
 * ## ⚠️ 只放「显示口径」，不放经济规则
 *
 * 这里没有余额、没有汇率、没有任何计算。余额永远是**算出来的**
 * （账本 delta 之和），汇率在 `domain/redeem.ts`。这个文件只回答
 * 「这个币叫什么、长什么样」。
 *
 * ## ⚠️ 老代码里还有字面量
 *
 * 两次改名都是**按名字精确替换**的（不能全局替换图标 —— `🌾` 同时是农作物的阶段图标、
 * 农场 tab 的图标）。所以老文件里仍写着字面量 `🎟️` / `🪙`。
 * 那些地方**行为是对的**，只是没走常量。新代码请用常量；
 * 顺手改到老文件时也可以换成常量（纯字符串，零风险）。
 */

/** 三套币的 id。和 `LedgerEntry` / `HarvestEntry` / 商城账本一一对应。 */
export type CurrencyId = 'points' | 'coupon' | 'mall'

export interface CurrencyDef {
  /** 界面上写的名字 */
  name: string
  /** 图标。三个**必须互不相同** —— 付款行是「图标 + 数字」并排的，重了就看不出在付哪种币 */
  emoji: string
  /** 用哪一档配色。见 `theme.css` 的色板 */
  tone: 'sun' | 'grass' | 'sky'
}

/**
 * ★★ **三套币互不相通**（spec §2.2）：
 *
 * ```
 *   积分  ⇸  商城币      商城币  ⇸  积分      钻石  ⇸  任何别的币
 * ```
 *
 * 唯一的例外是**兑换商城的付款口**：那里 `1 商城币 ≡ 1 积分`
 * （`planRedeemPayment`：先用光商城币，差额用积分补）。
 * 所以「商城币」的产出速率必须受控 —— 见 `domain/clawEconomy.ts` 的期望值不变量。
 */
export const CURRENCY: Record<CurrencyId, CurrencyDef> = {
  points: { name: '积分', emoji: '🪙', tone: 'sun' },
  // 2026-10-17：coupon（原「点券」）→「商城币」。持久化键 `harvestLedger` / `HarvestEntry` 一律不动。
  coupon: { name: '商城币', emoji: '🎟️', tone: 'grass' },
  // 2026-10-17：mall（原「商城币」）→「钻石」。持久化键 `mallLedger` / `MallEntry` 一律不动。
  mall: { name: '钻石', emoji: '💎', tone: 'sky' },
}

