/**
 * 游戏的**分类**（设置 → 游戏 → 游戏市场里那几个小标题）。
 *
 * ## 为什么单独一个文件
 *
 * 内置游戏在 `registry.ts`、随包发的插件在 `storefront.ts`，两边都要这个字段。
 * 让它俩互相 import 是错的：注册表是「有哪些游戏」的事实，内容文件是
 * 「怎么介绍它」。所以分类单独拎出来，两边都 import 它。
 *
 * ## 口径：按**玩起来是什么感觉 + 有没有产出**分
 *
 * ⚠️ 2026-10-25 加 `chill` 时改过一次这条口径。原来写的是「按玩法性质分，
 * 不按有没有产出分」，理由是「三款插件都会产出券，按产出分的话『纯玩』是空的」。
 * 甜点魔法学院进来之后这个理由不成立了：它**一分券都不产出**
 * （`expectedPayout: 0`，插件里一次 `mintVoucher` 都没调）。
 *
 * 硬把它塞进 `play` 的话，`play` 那句说明「花积分换币，产出看运气」就是假的 ——
 * 它连币都没有。家长按那句说明做判断，等于被骗。所以宁可加一类。
 *
 * 每一行上照样标真实的适龄 / 时长 / 体积 —— **分类是判断，数字是事实，两者不混**。
 *
 * ⚠️ 改这个字段之前先想清楚：它出现在家长看的那一页上，
 * 而家长用这一栏决定「给不给孩子玩」。
 */
export type GameKind = 'think' | 'play' | 'chill'

