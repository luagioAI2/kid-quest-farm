/* ============================================================
   在线版 · 「从备份恢复」和「清空全部数据」在账号下做不了什么
   ------------------------------------------------------------
   这两张卡本来是**本地版**的能力：数据就在这台设备的 Dexie 里，
   导入 = 覆盖它，清空 = 删掉它。

   在线版的数据在服务端（`pullFromServer` 每次刷新都「先清后写」），
   Dexie 只是读缓存。于是：

     · **从备份恢复**：备份里的行 id 没有 `srv_` 前缀，拉取时不会被清掉
       ⇒ 和服务端那份**叠加**（余额显示成两份之和、任务重复出现），
       而服务端根本不认这些行 —— 孩子看到一个很大的余额，一花就说不够。
     · **清空全部数据**：清完 Dexie，下一次 `refresh` 又把服务端那份拉回来
       ⇒ 提示「已重新开始」，几秒后记录全回来了。

   两张卡都会「先承诺、再当场否认」，所以在线版**直接不提供**，
   并把原因写在卡上。真要迁移 / 清空，得服务端有对应接口
   （迁移是另一期的事，见 `docs/online-version.md` §7.15）。
   ============================================================ */

/** 为什么不能从备份恢复 —— 同一句话给 toast 和卡片用（别各写一份） */
export const IMPORT_REFUSAL =
  '在线版不能从备份恢复：记录都在账号里，导入的旧账会和账号里那份叠在一起（余额显示成两份、任务重复出现）。换设备直接登录同一个账号就行。'

/** 为什么不能一键清空 */
export const RESET_REFUSAL =
  '在线版的记录在账号里，App 里清不掉 —— 清了下次打开又会回来。要让孩子重新开始，请先退出登录（记录还在账号里，登录就回来）。'

export type OnlineDataOp = 'import' | 'reset'

/**
 * 这道闸门挡不挡：`null` = 放行。
 *
 * ★ 抽成纯函数是因为 `isOnlineMode` 是**构建期常量**（`vitest.config.ts` 钉成
 *   `local`），在 store 里根本造不出「在线版」来测；规则留在这里就能单测。
 * ★ 闸门必须留在 store（`importBackup` / `resetAll` 开头），不能只靠界面不画按钮 ——
 *   调试桥和以后的批量脚本都绕得过按钮（同「门槛放 store，不放按钮」）。
 */
export function onlineDataOpRefusal(online: boolean, op: OnlineDataOp): string | null {
  if (!online) return null
  return op === 'import' ? IMPORT_REFUSAL : RESET_REFUSAL
}
